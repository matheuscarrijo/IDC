"""Fill the monthly report (``idc-update-YYYYMM.tex``) from the local template and the processed data.

The template (``outputs/report/template-latex/template.tex``, not versioned) holds the fixed text and the
structure of the report.  Everything that changes from month to month is generated by ``src.report_text`` and
written here:

* the date macros of the preamble (reference, previous and publication months, release, cover date);
* the blocks of generated text, each between ``% >>> IDC (name): ...`` and ``% <<< IDC (name)`` comment lines.

The blocks are regenerated in place on every run, so the step can be repeated after ``python3 main.py`` without
losing what was added by hand to the report: the optional ``Revisões dos dados`` section and the optional comment
of the authors (``quote`` environment at the end of ``Trajetória dos índices``).  The report never refers to
any other document, and its numbers must not be changed by hand: fix the data and run the step again.

The processed data must belong to the release of the report (the latest workbook in ``data/raw/`` is the one of
``PERIOD``) and to its reference month (``\\mesref`` of an already filled report); otherwise nothing is written,
so that numbers of another release never enter a report.

Command line (from the repository root, after ``python3 main.py``)::

    python3 -m src.fill_report 202610            # creates or updates outputs/report/update-202610/idc-update-202610.tex
    python3 -m src.fill_report 202610 --check    # only validates the current file
"""
from __future__ import annotations

import argparse
import re
import shutil
import sys
from pathlib import Path

import pandas as pd

from src import low_income as LI
from src import report_text as RT
from src.pt_format import mes

REPORT_DIR = "outputs/report/update-{period}"
REPORT_NAME = "idc-update-{period}.tex"
TEMPLATE_DIR = Path("outputs/report/template-latex")
FIGURES_DIR = Path("outputs/figures")
RAW_DIR = Path("data/raw")
FIGURES = ("index.png", "index_since_2022.png", "index_12m.png", "components_raw.png")

BEGIN = "% >>> IDC ({name}): gerado por src.fill_report; revise o texto sem alterar os números"
END = "% <<< IDC ({name})"
_BLOCK = re.compile(r"(?P<begin>% >>> IDC \((?P<name>[^)]+)\):[^\n]*\n)(?P<body>.*?)(?P<end>% <<< IDC \((?P=name)\))", re.S)
BLOCKS = ("apresentacao", "resumo", "tabela", "geral", "baixa-renda", "trajetoria", "nota-baixa-renda", "anexo")

SECTION_TRAJECTORY = r"\section{Trajetória dos índices}"
NOTES = r"\section*{Notas}"
ANNEX = r"\section*{Anexo de figuras}"

_MONTHS_FULL = {1: "Janeiro", 2: "Fevereiro", 3: "Março", 4: "Abril", 5: "Maio", 6: "Junho", 7: "Julho",
                8: "Agosto", 9: "Setembro", 10: "Outubro", 11: "Novembro", 12: "Dezembro"}


def macros(period: str, geral: RT.FatosIndice) -> dict[str, str]:
    """Values of the date macros of the preamble."""
    published = pd.Timestamp(f"{period[:4]}-{period[4:]}-01")
    return {
        "mesreferencia": RT.mes_extenso(geral.t1),
        "mesref": mes(geral.t1),
        "mesanterior": mes(geral.tprev),
        "competencia": period,
        "mespublicacao": RT.mes_extenso(published),
        "reportdate": f"{_MONTHS_FULL[published.month]} de {published.year}",
    }


def report_month(tex: str) -> str | None:
    """Reference month written in the report (``\\mesref``), or ``None`` when the macro is missing."""
    found = re.search(r"^\\newcommand\{\\mesref\}\{(.*?)\}[ \t]*(?:%.*)?$", tex, re.M)
    return found.group(1) if found else None


def _set_macro(tex: str, name: str, value: str) -> str:
    pattern = re.compile(rf"^(\\newcommand\{{\\{name}\}}\{{).*?(\}}[ \t]*(?:%.*)?)$", re.M)
    new, n = pattern.subn(lambda m: m.group(1) + value + m.group(2), tex, count=1)
    if n != 1:
        raise ValueError(f"macro \\{name} não encontrada no relatório; ele precisa manter o preâmbulo do template")
    return new


def blocks(period: str, geral: RT.FatosIndice, baixa: RT.FatosIndice | None, resultado: LI.Resultado) -> dict[str, str]:
    """Body of every generated block for this edition."""
    return {
        "apresentacao": RT.apresentacao(period, baixa is not None),
        "resumo": RT.resumo(geral, baixa),
        "tabela": RT.tabela(geral, baixa, period),
        "geral": RT.resultados_geral(geral),
        "baixa-renda": RT.resultados_baixa_renda(geral, baixa) if baixa is not None else RT.baixa_renda_indisponivel(resultado),
        "trajetoria": RT.trajetoria(geral, baixa),
        "nota-baixa-renda": RT.nota_baixa_renda() if baixa is not None else "",
        "anexo": RT.anexo(geral, baixa),
    }


def fill(tex: str, period: str, geral: RT.FatosIndice, baixa: RT.FatosIndice | None, resultado: LI.Resultado) -> str:
    """Return ``tex`` with the macros and the generated blocks of this edition (regenerating those of a previous run)."""
    written = report_month(tex)
    if written is None:
        raise ValueError("macro \\mesref ausente; o relatório precisa manter o preâmbulo do template")
    if "placeholder" not in written and written != mes(geral.t1):
        raise ValueError(f"o relatório trata de {written}, mas os dados processados terminam em {mes(geral.t1)}; "
                         "rode python3 main.py com o release do relatório")
    for name, value in macros(period, geral).items():
        tex = _set_macro(tex, name, value)
    found = [m.group("name") for m in _BLOCK.finditer(tex)]
    missing = [name for name in BLOCKS if name not in found]
    if missing:
        raise ValueError(f"bloco gerado ausente no relatório: {', '.join(missing)}. O relatório precisa manter a estrutura do template.")
    bodies = blocks(period, geral, baixa, resultado)

    def replace(m: re.Match) -> str:
        body = bodies.get(m.group("name"))
        if body is None:
            return m.group(0)
        return m.group("begin") + (body.strip() + "\n" if body.strip() else "") + m.group("end")

    return _BLOCK.sub(replace, tex)


def _body(tex: str) -> str:
    """The visible text of the document body (LaTeX comments removed)."""
    start = tex.find(r"\begin{document}")
    visible = tex[start if start >= 0 else 0:]
    return "\n".join(re.sub(r"(?<!\\)%.*", "", line) for line in visible.splitlines())


def invalid_bold(tex: str) -> list[str]:
    """Bold spans that break the style rule: outside the tables, only the labels of the component items are bold."""
    text = re.sub(r"\\begin\{table\}.*?\\end\{table\}", "", _body(tex), flags=re.S)
    return [m.group(1) for m in re.finditer(r"\\textbf\{([^{}]*)\}", text) if m.group(1).strip() not in RT.ROTULOS_DOS_ITENS]


def validate(tex: str) -> list[str]:
    """Problems that must be fixed before the report is compiled (empty when everything is in order)."""
    problems = []
    body = _body(tex)
    found = [m.group("name") for m in _BLOCK.finditer(tex)]
    problems += [f"bloco gerado ausente: {name}" for name in BLOCKS if name not in found]
    if r"\placeholder{" in body:
        problems.append("o relatório ainda tem \\placeholder{...}")
    if re.search(r"ap[êe]ndice", body, re.I):
        problems.append("o relatório menciona o apêndice; a nota principal não pode citá-lo")
    problems += [f"negrito fora da regra: {b}" for b in invalid_bold(tex)]
    if "tab:componentes" not in tex:
        problems.append("a tabela de resultados perdeu o rótulo tab:componentes")
    trajectory, notes = body.find(SECTION_TRAJECTORY), body.find(NOTES)
    for m in re.finditer(r"\\begin\{quote\}", body):
        if not (0 <= trajectory < m.start() < notes):
            problems.append("o comentário dos autores (quote) só pode ficar no fim de Trajetória dos índices")
    return problems


def _latest_release(raw_dir: Path = RAW_DIR) -> str | None:
    periods = sorted(p.name for p in raw_dir.glob("[0-9]" * 6) if p.is_dir())
    return periods[-1] if periods else None


def facts_from_data(data_dir: Path = Path("data/processed")) -> tuple[RT.FatosIndice, RT.FatosIndice | None, LI.Resultado]:
    """Facts of the two indices from the files written by ``main.py`` (``None`` for the IDC Baixa Renda when unavailable)."""
    comp = pd.read_csv(data_dir / "components_raw.csv", index_col=0, parse_dates=True)
    idx = pd.read_csv(data_dir / "index.csv", index_col=0, parse_dates=True)
    geral = RT.fatos_geral(comp, idx)
    resultado = LI.carregar(data_dir / "low_income_idc.csv", data_dir / "low_income_status.json")
    if not resultado.disponivel:
        return geral, None, resultado
    if resultado.t1 != geral.t1:
        raise ValueError(f"o IDC Baixa Renda termina em {mes(resultado.t1)}, mas o IDC Geral termina em {mes(geral.t1)}; rode python3 main.py de novo")
    return geral, RT.fatos_baixa_renda(resultado.serie, geral), resultado


def prepare(period: str, template_dir: Path = TEMPLATE_DIR, figures_dir: Path = FIGURES_DIR, folder: Path | None = None) -> Path:
    """Create the report directory (copying the template once) and refresh the logo and figures; returns the .tex path."""
    folder = folder or Path(REPORT_DIR.format(period=period))
    path = folder / REPORT_NAME.format(period=period)
    for name in ("template.tex", "logo.png"):
        if not (template_dir / name).exists():
            raise FileNotFoundError(f"arquivo local do template ausente: {template_dir / name}")
    missing = [name for name in FIGURES if not (figures_dir / name).exists()]
    if missing:
        raise FileNotFoundError(f"figuras ausentes em {figures_dir}: {', '.join(missing)}; rode python3 main.py")
    folder.mkdir(parents=True, exist_ok=True)
    if not path.exists():
        shutil.copyfile(template_dir / "template.tex", path)
    shutil.copyfile(template_dir / "logo.png", folder / "logo.png")
    for name in FIGURES:
        shutil.copyfile(figures_dir / name, folder / name)
    return path


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Preenche o relatório mensal do IDC a partir do template e dos dados processados.")
    parser.add_argument("period", help="competência da divulgação do BCB (AAAAMM)")
    parser.add_argument("--check", action="store_true", help="só valida o arquivo atual, sem escrever")
    args = parser.parse_args(argv)
    path = Path(REPORT_DIR.format(period=args.period)) / REPORT_NAME.format(period=args.period)
    if args.check:
        if not path.exists():
            print(f"Relatório não encontrado: {path}", file=sys.stderr)
            return 1
        problems = validate(path.read_text(encoding="utf-8"))
        print("\n".join(problems) if problems else "Relatório válido.")
        return 1 if problems else 0
    try:
        latest = _latest_release()
        if latest != args.period:
            raise ValueError(f"o release mais recente em {RAW_DIR} é {latest}, não {args.period}; "
                             "os dados processados não pertencem ao release do relatório")
        geral, baixa, resultado = facts_from_data()
        path = prepare(args.period)
        new = fill(path.read_text(encoding="utf-8"), args.period, geral, baixa, resultado)
    except (ValueError, FileNotFoundError) as exc:
        print(f"Falha: {exc}", file=sys.stderr)
        return 1
    problems = validate(new)
    if problems:
        print("Falha na validação:\n  " + "\n  ".join(problems), file=sys.stderr)
        return 1
    path.write_text(new, encoding="utf-8")
    status = "com o IDC Baixa Renda" if baixa is not None else f"sem o IDC Baixa Renda ({resultado.motivo})"
    print(f"Relatório preenchido {status}: {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
